const originalTextValues = new WeakMap<Text, string>();
const trackedTextNodes = new Set<Text>();
const originalAttributeValues = new WeakMap<Element, Map<string, string | null>>();
const trackedElements = new Set<Element>();

function restoreLocale() {
  trackedTextNodes.forEach(textNode => {
    const original = originalTextValues.get(textNode);
    if (original !== undefined && textNode.isConnected) textNode.nodeValue = original;
  });
  trackedElements.forEach(element => {
    const attributes = originalAttributeValues.get(element);
    if (!attributes || !element.isConnected) return;
    attributes.forEach((value, attribute) => {
      if (value === null) element.removeAttribute(attribute);
      else element.setAttribute(attribute, value);
    });
  });
}

function translateDocument(root: ParentNode) {
  if (typeof document === "undefined") return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const textNodes: Text[] = [];
  let node: Node | null;
  while ((node = walker.nextNode())) {
    const parent = node.parentElement;
    if (parent && !["SCRIPT", "STYLE", "NOSCRIPT"].includes(parent.tagName) && !parent.closest("[data-locale-preserve]")) textNodes.push(node as Text);
  }
  textNodes.forEach(textNode => {
    const current = textNode.nodeValue ?? "";
    const knownOriginal = originalTextValues.get(textNode);
    const translatedKnownOriginal = knownOriginal === undefined ? undefined : translateCore(knownOriginal);
    const original = knownOriginal === undefined || (current !== knownOriginal && current !== translatedKnownOriginal) ? current : knownOriginal;
    originalTextValues.set(textNode, original);
    trackedTextNodes.add(textNode);
    textNode.nodeValue = translateCore(original);
  });
  root.querySelectorAll?.("[aria-label], [placeholder], [title], [alt]").forEach(element => {
    let attributes = originalAttributeValues.get(element);
    if (!attributes) {
      attributes = new Map<string, string | null>();
      originalAttributeValues.set(element, attributes);
      trackedElements.add(element);
    }
    ["aria-label", "placeholder", "title", "alt"].forEach(attribute => {
      if (element.closest("[data-locale-preserve]")) return;
      const value = element.getAttribute(attribute);
      const knownOriginal = attributes?.get(attribute);
      const translatedKnownOriginal = knownOriginal === undefined || knownOriginal === null ? undefined : translateCore(knownOriginal);
      const original = knownOriginal === undefined || (value !== knownOriginal && value !== translatedKnownOriginal) ? value : knownOriginal;
      attributes?.set(attribute, original);
      if (value) element.setAttribute(attribute, translateCore(original ?? value));
    });
  });
}

